import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context = vm.createContext({ console, setTimeout, clearTimeout, AbortController });
vm.runInContext(fs.readFileSync(new URL('./translation-readiness.js', import.meta.url), 'utf8'), context);
const createManager = context.DubTranslationReadiness.createManager;
const pair = { sourceLanguage: 'de', targetLanguage: 'ar' };
let creates = 0;
let availability = 'downloadable';
let complete;
let progress;
const api = { availability: async () => availability, create(options) {
  creates++;
  options.monitor({ addEventListener(_name, listener) { progress = listener; } });
  return new Promise(resolve => { complete = resolve; });
}};
const manager = createManager(api, { timeout: 20, preparationTimeout: 100 });
assert.equal((await manager.check(pair)).state, 'preparation-required');
assert.equal(creates, 0, 'checking must not start first-use downloads');
const updates = [];
const pending = manager.prepare(pair, update => updates.push(update));
assert.equal(creates, 1, 'create must run synchronously in the click call stack');
progress({ loaded: .25 });
assert.equal(updates.at(-1).progress, 25);
progress({ loaded: 1 });
assert.equal(updates.at(-1).state, 'downloading', '100% alone is not ready');
complete({ translate: async text => `AR:${text}`, destroy() {} });
await pending;
assert.equal(updates.at(-1).state, 'ready');
assert.equal(await manager.translate(pair, 'helfen'), 'AR:helfen');
const stalled = createManager({ availability: async () => 'available', create: async () => ({ translate: () => new Promise(() => {}), destroy() {} }) }, { timeout: 10 });
await assert.rejects(stalled.translate(pair, 'helfen'), /timed out/);
const lateUpdates = [];
let lateComplete;
let destroyed = false;
const late = createManager({ create: () => new Promise(resolve => { lateComplete = resolve; }) }, { preparationTimeout: 10 });
await assert.rejects(late.prepare(pair, update => lateUpdates.push(update)), /timed out/);
lateComplete({ destroy() { destroyed = true; } });
await Promise.resolve(); await Promise.resolve();
assert.equal(destroyed, true);
assert.ok(!lateUpdates.some(update => update.state === 'ready'));
assert.equal((await createManager(null).check(pair)).state, 'unavailable');
assert.equal((await createManager(null).check({ sourceLanguage: 'de', targetLanguage: 'de' })).state, 'ready');
await assert.rejects(createManager({ availability: async () => 'available', create: async () => { throw new Error('browser preparation failed'); } }).check(pair), /browser preparation failed/);
console.log('Translation preparation, real progress contract, timeout and late-response tests passed (simulated API)');
